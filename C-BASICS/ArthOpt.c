#include <stdio.h>
int main()
{
    int a, b;

    printf("enter a:");
    scanf("%d", &a);

    printf("enter b:");
    scanf("%d", &b);

    printf("sum of the two numbers is %d", a + b);
    printf("\n multiplication of the two numbers is %d", a * b);
    printf("\n subraction of the two numbers is %d", a - b);
    printf("\n division of the two numbers is %d", a / b);
    printf("\n reminder of the two numbers is %d", a % b);
    return 0;
}
